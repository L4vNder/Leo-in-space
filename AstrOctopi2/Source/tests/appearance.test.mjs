import assert from 'node:assert/strict';
import {PALETTES,parseAppearance,readableInk} from '../dist/appearance.js';
const orig=PALETTES.orbit;
assert.equal(orig.light.background,'#f2f8fd');
assert.equal(orig.light.search,'#e6f1fb');
assert.equal(orig.light.accent,'#7fb4e6');
assert.equal(orig.dark.background,'#0b0c12');
assert.equal(orig.dark.surface,'#161826');
assert.equal(orig.dark.accent,'#f6e7a6');
const defaultState=parseAppearance(null);
assert.equal(defaultState.mode,'light');
assert.equal(defaultState.palette,'orbit');
assert.equal(defaultState.custom.dark.search,null);
const decoded=parseAppearance(JSON.stringify({mode:'dark',palette:'seafoam',custom:{light:{search:'#ABCDEF'},dark:{accent:'#123456',background:'red;all:unset',search:'url(evil)'}}}));
assert.equal(decoded.mode,'dark');
assert.equal(decoded.palette,'seafoam');
assert.equal(decoded.custom.light.search,'#abcdef');
assert.equal(decoded.custom.dark.accent,'#123456');
assert.equal(decoded.custom.dark.background,null);
assert.equal(decoded.custom.dark.search,null);
assert.equal(parseAppearance('{broken').palette,'orbit');
assert.equal(parseAppearance({mode:'other',palette:'other'}).mode,'light');
assert.equal(readableInk('#ffffff'),'#171c2b');
assert.equal(readableInk('#000000'),'#ffffff');
console.log('PASS: original AstrOctopi palette, persistent settings format, corrupted-data fallback, validated custom colors, and readable search contrast.');
